import { FORBIDDEN_PHRASES } from '@ss-deals/core';

export function helpText(dailyPostLimit: number): string {
  return [
    'Send one deal per message. A photo uses the same fields in its caption.',
    '',
    'https://www.amazon.in/dp/B0XXXXXXXX',
    'title: Product name',
    'price: 1,499',
    'old: 2,999',
    'verified: yes',
    'offer: Bank offer',
    'short: https://amzn.to/example',
    'preview: on',
    '- Highlight',
    '',
    'Rules:',
    '- title and price are required.',
    '- price is a whole number of rupees: 1499, 1,499, or ₹1,499.',
    '- old is optional and must be higher than price.',
    '- verified is yes or no. The default is no.',
    '- When verified is yes, the old price is struck through on the deal-price line and the next line is the percent off.',
    '- When verified is not yes, an old price is shown as Listed at, with no percentage.',
    '- POST_FOOTER, when configured, is added in italics at the end. An empty footer adds nothing.',
    '- offer is optional and must be 120 characters or fewer.',
    '- short is an optional https link on an allowed host. It is shown instead of the tagged link. The full amazon.in link is still required.',
    '- preview is on or off. The default is on. Off disables the link preview.',
    '- Up to 3 lines starting with - become highlights.',
    '- Use a full amazon.in /dp/ or /gp/product/ link. A short link on its own is rejected.',
    '- Photos are posted with the same file Telegram already has. The bot does not download the image.',
    '- Nothing is posted until you tap Post to channel.',
    '- The same product within 14 days needs a second confirmation.',
    `- The daily limit is ${dailyPostLimit} posts. Going over it needs an extra confirmation.`,
    `- Avoid these words: ${FORBIDDEN_PHRASES.join(', ')}.`,
  ].join('\n');
}
